package com.bilgeadam.forloop;

public class ForLoopExample {
	
	
	public static void main(String[] args) {
		
		int a = 0; //initialize value
		
		//condition
		while (a <= 20) {
			System.out.println(a);
			a++; //increment value
		}
		
		System.out.println("************************");
		
		for (int b = 0 ; b <= 20 ; b++ ) {
			System.out.println(b);
		}
		
		
		
	}

}
